// Regenerates src/core/legacy-skill-hashes.ts: the content hash of every pack
// each released CLI installed before stamps carried a contentHash. Installs each
// version from npm into a temp project and hashes the result with this build's
// hashPack. Run `npm run build` first.
import { execFileSync } from "node:child_process"
import { existsSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { hashPack } from "../dist/src/core/skill-install.js"

const VERSIONS = [
  "1.11.0", "1.11.1", "1.11.2", "1.11.3", "1.11.4", "1.11.5", "1.11.6",
  "1.11.7", "1.12.0", "1.12.1", "1.13.0"
]

const table = {}
for (const version of VERSIONS) {
  const dir = mkdtempSync(join(tmpdir(), `legacy-skills-${version}-`))
  execFileSync(
    "npx",
    ["-y", `@cloudcruise/cli@${version}`, "install", "--skills", "--target", "claude"],
    { cwd: dir, env: { ...process.env, HOME: dir, NO_UPDATE_NOTIFIER: "1" }, stdio: "ignore" }
  )
  const root = join(dir, ".claude", "skills")
  table[version] = {}
  for (const pack of readdirSync(root).sort()) {
    const manifest = join(root, pack, ".cloudcruise-skill.json")
    if (!existsSync(manifest)) continue
    if (JSON.parse(readFileSync(manifest, "utf-8")).cliVersion !== version) {
      throw new Error(`${version}/${pack}: unexpected stamp`)
    }
    table[version][pack] = hashPack(join(root, pack))
  }
}

const out = new URL("../src/core/legacy-skill-hashes.ts", import.meta.url)
writeFileSync(
  out,
  `// Generated by scripts/legacy-skill-hashes.mjs. Content hash of each pack as
// released CLIs installed it before stamps carried a contentHash, so
// auto-refresh can tell their unedited packs from edited ones.
export const LEGACY_SKILL_HASHES: Record<string, Record<string, string>> = ${JSON.stringify(table, null, 2)}
`
)
